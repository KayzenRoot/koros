-- KOR-PM04-WO-004: tamper-evident audit chain, tenant budgets and kill switch.

ALTER TABLE audit_events
  ADD COLUMN IF NOT EXISTS audit_seq bigint GENERATED BY DEFAULT AS IDENTITY,
  ADD COLUMN IF NOT EXISTS correlation_id uuid,
  ADD COLUMN IF NOT EXISTS prev_hash text,
  ADD COLUMN IF NOT EXISTS event_hash text;

ALTER TABLE audit_events DROP CONSTRAINT IF EXISTS audit_events_prev_hash_check;
ALTER TABLE audit_events ADD CONSTRAINT audit_events_prev_hash_check
  CHECK (prev_hash IS NULL OR length(prev_hash) = 64);

ALTER TABLE audit_events DROP CONSTRAINT IF EXISTS audit_events_event_hash_check;
ALTER TABLE audit_events ADD CONSTRAINT audit_events_event_hash_check
  CHECK (event_hash IS NULL OR length(event_hash) = 64);

CREATE UNIQUE INDEX IF NOT EXISTS uq_audit_events_seq ON audit_events (audit_seq);
CREATE INDEX IF NOT EXISTS idx_audit_tenant_correlation
  ON audit_events (tenant_id, correlation_id);

ALTER TABLE usage_ledger
  ADD COLUMN IF NOT EXISTS correlation_id uuid,
  ADD COLUMN IF NOT EXISTS operation text NOT NULL DEFAULT 'synthetic.legacy',
  ADD COLUMN IF NOT EXISTS status text NOT NULL DEFAULT 'SETTLED',
  ADD COLUMN IF NOT EXISTS updated_at timestamptz NOT NULL DEFAULT now();

ALTER TABLE usage_ledger DROP CONSTRAINT IF EXISTS usage_ledger_status_check;
ALTER TABLE usage_ledger ADD CONSTRAINT usage_ledger_status_check
  CHECK (status IN ('RESERVED', 'SETTLED', 'RELEASED'));

CREATE INDEX IF NOT EXISTS idx_usage_tenant_status_created
  ON usage_ledger (tenant_id, status, created_at);

CREATE TABLE IF NOT EXISTS budget_policies (
  tenant_id uuid PRIMARY KEY REFERENCES organizations(tenant_id) ON DELETE CASCADE,
  period_start timestamptz NOT NULL,
  period_end timestamptz NOT NULL,
  max_tokens integer NOT NULL CHECK (max_tokens >= 0),
  max_cost numeric(12, 4) NOT NULL CHECK (max_cost >= 0),
  updated_at timestamptz NOT NULL DEFAULT now(),
  updated_by uuid REFERENCES users(user_id),
  CHECK (period_end > period_start)
);

CREATE TABLE IF NOT EXISTS tenant_controls (
  tenant_id uuid PRIMARY KEY REFERENCES organizations(tenant_id) ON DELETE CASCADE,
  kill_switch_active boolean NOT NULL DEFAULT false,
  kill_switch_reason text,
  updated_at timestamptz NOT NULL DEFAULT now(),
  updated_by uuid REFERENCES users(user_id),
  CHECK (
    kill_switch_active = false
    OR (kill_switch_reason IS NOT NULL AND length(kill_switch_reason) BETWEEN 1 AND 500)
  )
);

ALTER TABLE budget_policies ENABLE ROW LEVEL SECURITY;
ALTER TABLE tenant_controls ENABLE ROW LEVEL SECURITY;

CREATE POLICY tenant_isolation ON budget_policies
  USING (tenant_id = nullif(current_setting('app.tenant_id', true), '')::uuid)
  WITH CHECK (tenant_id = nullif(current_setting('app.tenant_id', true), '')::uuid);
CREATE POLICY tenant_isolation ON tenant_controls
  USING (tenant_id = nullif(current_setting('app.tenant_id', true), '')::uuid)
  WITH CHECK (tenant_id = nullif(current_setting('app.tenant_id', true), '')::uuid);

GRANT SELECT, INSERT, UPDATE, DELETE ON budget_policies, tenant_controls TO koros_app;

COMMENT ON COLUMN audit_events.event_hash IS
  'SHA-256 chain hash over the redacted event and prev_hash; legacy rows may be NULL.';
COMMENT ON COLUMN tenant_controls.kill_switch_active IS
  'When true, paid/outbound work must fail closed before claiming or calling a provider.';
